export const textWidth = (text, scale = 1, isBig = false) => Math.max(0, text.length * (isBig ? 6 : 4) * scale - scale);

// align: 'left' | 'center' | 'right'. Shadow draws a 1-scale offset copy underneath.
// big: use the 5×7 heading font instead of the 3×5 one.
export function drawText(ctx, text, x, y, { color = '#fff', scale = 1, align = 'left', shadow = '#000', big = false } = {}) {
  const str = String(text).toUpperCase();
  const w = textWidth(str, scale, big);
  const cx = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  y = Math.round(y);
  if (shadow) draw(ctx, str, cx + scale, y + scale, scale, shadow, big);
  draw(ctx, str, cx, y, scale, color, big);
}

function draw(ctx, str, x, y, scale, color, big) {
  const [set, cols, cells] = big ? [BIG, 5, 35] : [GLYPHS, 3, 15];
  ctx.fillStyle = color;
  for (const ch of str) {
    const g = set[ch] || set['?'];
    for (let i = 0; i < cells; i++) {
      if (g[i] === '1') ctx.fillRect(x + (i % cols) * scale, y + Math.floor(i / cols) * scale, scale, scale);
    }
    x += (cols + 1) * scale;
  }
}
